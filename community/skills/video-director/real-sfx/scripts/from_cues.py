def expand_typing(events, rate=11.0):
    """A key event with a length is a STRETCH of typing (ui_events.py or the author: "typing from 19.99 for 0.36 s,
    99 characters"): it becomes keystrokes at the stated count (n / chars) over the stretch, else `rate` a second,
    unevenly spaced like a hand. Events without a length stay as they are."""
    out, made = [], 0
    for e in events:
        ln = e.get("len")
        if e.get("ck") == "key" and ln and ln >= 0.25 and not e.get("custom"):
            raw = e.get("raw") if isinstance(e.get("raw"), dict) else {}
            n = next((raw[k] for k in ("n", "chars", "count", "keys") if isinstance(raw.get(k), (int, float))), None)
            n = int(n) if n else max(2, int(round(ln * rate)))
            r = random.Random(int(e["t"] * 1000) + n)
            t = e["t"]
            step = ln / max(1, n)
            for k in range(n):
                d = dict(e)
                d["t"] = round(t + k * step + r.uniform(-0.25, 0.25) * step, 3)
                d["len"] = None
                d["g"] = e["g"]
                out.append(d)
            made += n - 1
        else:
            out.append(e)
    if made:
        print(f"typing: {made} keystroke(s) made from stretches of typing (at the stated count, else "
              f"{rate:g}/s: --type-rate)")
    return sorted(out, key=lambda x: x["t"])


def fuse_events(events, gap, span=0.06):
    """Events of one kind closer than `gap` seconds are ONE sound to the ear (the precedence effect): a cluster of
    beads 4-40 ms apart is a rattle, not nine hits. Each cluster (at most `span` long) becomes its first event at
    the loudest gain of the cluster. Returns (events, how many were folded)."""
    if gap <= 0:
        return events, 0
    by_kind, out, folded = {}, [], 0
    for e in events:
        by_kind.setdefault(e["ck"], []).append(e)
    drop = set()
    for kind, es in by_kind.items():
        head = None
        for e in sorted(es, key=lambda x: x["t"]):
            if head is not None and e["t"] - head["_last"] <= gap and e["t"] - head["t"] <= span:
                head["g"] = max(head["g"], e["g"])
                head["_last"] = e["t"]
                drop.add(id(e))
                folded += 1
            else:
                head = e
                head["_last"] = e["t"]
    for e in events:
        if id(e) not in drop:
            e.pop("_last", None)
            out.append(e)
    return out, folded


def thin_runs(events, max_rate):
    """Drop every other event of a run that is faster than max_rate per second. Returns (kept, dropped)."""
    kept, dropped = [], 0
    by_kind = {}
    for e in events:
        by_kind.setdefault(e["ck"], []).append(e)
    keep_ids = set()
    for kind, es in by_kind.items():
        run = []
        for e in es + [None]:
            if e is not None and (not run or e["t"] - run[-1]["t"] <= THIN_GAP):
                run.append(e)
                continue
            if run:
                span = run[-1]["t"] - run[0]["t"]
                rate = (len(run) - 1) / span if span > 0 else 0
                step = 1
                if len(run) >= 4 and rate > max_rate:
                    step = int(math.ceil(rate / max_rate))
                for i, r in enumerate(run):
                    if i % step == 0 or i == len(run) - 1:
                        keep_ids.add(id(r))
            run = [e] if e is not None else []
    for e in events:
        if id(e) in keep_ids:
            kept.append(e)
        else:
            dropped += 1
    return kept, dropped


