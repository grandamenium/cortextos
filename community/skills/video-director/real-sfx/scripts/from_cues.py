def find_stems(root):
    """The project's own audio stems: (base files, synthesized-effect files). A folder named stems/ with files such
    as voice.wav, music.wav, sfx.wav, transitions.wav is what a score builder writes next to the final mix."""
    for rel in ("assets/audio/stems", "audio/stems", "assets/stems", "stems", "assets/audio"):
        d = Path(root) / rel
        if not d.is_dir():
            continue
        files = [f for f in sorted(d.iterdir()) if f.suffix.lower() in AUDIO_SUFFIX]
        base, synth = [], []
        for f in files:
            n = f.stem.lower()
            if any(w in n for w in SFX_STEM_WORDS) and not any(w in n for w in ("voice", "vo_", "music")):
                synth.append(f)
            elif any(w in n for w in BASE_STEM_WORDS):
                base.append(f)
        if base and synth:
            return base, synth
    return [], []


def probe_duration(path):
    r = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(path)],
                       capture_output=True, text=True)
    try:
        return float(r.stdout.strip())
    except ValueError:
        return 0.0


def envelope(samples, rate, hop=0.02):
    w = max(1, int(rate * hop))
    out = []
    for i in range(0, len(samples) - w + 1, w):
        r = math.sqrt(sum(v * v for v in samples[i:i + w]) / w) / 32768.0
        out.append(20 * math.log10(r) if r > 1e-5 else -100.0)
    return out


def verify_stems(stems, video):
    """Do the project's stems belong to THIS render? Their sum is the project's own mix (before its master gain), so
    the loudness over time has to follow the render's audio. A project that is re-timed after the voice fit keeps
    the stems of the newest cut next to the renders of older ones. Returns a dict (ok, durations, best lag, corr)."""
    vdur = probe_duration(video)
    sdur = max((probe_duration(s) for s in stems), default=0.0)
    rate = 8000
    r, _ = decode_mono(video, rate)
    n = len(r)
    acc = None
    for s in stems:
        x, _ = decode_mono(s, rate)
        if acc is None:
            acc = [float(v) for v in x]
        else:
            if len(x) > len(acc):
                acc.extend([0.0] * (len(x) - len(acc)))
            for i, v in enumerate(x):
                acc[i] += v
    if not n or not acc:
        return {"ok": False, "video_s": round(vdur, 2), "stems_s": round(sdur, 2), "corr": None, "lag_s": None}
    ea = envelope([max(-32768, min(32767, int(v))) for v in acc], rate)
    er = envelope(r, rate)
    m = min(len(ea), len(er))
    best = (-2.0, 0)
    for lag in range(-20, 21):                      # +-0.4 s in steps of 20 ms
        xs, ys = [], []
        for i in range(m):
            j = i + lag
            if 0 <= j < m and er[i] > -70 and ea[j] > -70:
                xs.append(er[i])
                ys.append(ea[j])
        if len(xs) < 50:
            continue
        mx, my = sum(xs) / len(xs), sum(ys) / len(ys)
        sxx = sum((x - mx) ** 2 for x in xs)
        syy = sum((y - my) ** 2 for y in ys)
        if sxx > 0 and syy > 0:
            c = sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / math.sqrt(sxx * syy)
            if c > best[0]:
                best = (c, lag)
    corr, lag = best
    ok = abs(vdur - sdur) <= 0.2 and corr >= 0.85 and abs(lag) <= 2
    return {"ok": bool(ok), "video_s": round(vdur, 2), "stems_s": round(sdur, 2), "corr": round(corr, 2),
            "lag_s": round(lag * 0.02, 2)}


def matching_renders(root, seconds, exclude=None, tol=0.2, limit=5):
    """Renders of the project whose length equals the stems': the ones the stems were made for."""
    out = []
    for dp, dns, fns in os.walk(root):
        dns[:] = [d for d in dns if d not in {"node_modules", ".git", ".hyperframes", "snapshots", "assets",
                                              "after-effects", "vendor"} and
                  len(Path(dp, d).relative_to(root).parts) < 3]
        for fn in fns:
            if fn.lower().endswith((".mp4", ".mov", ".m4v", ".mkv")):
                p = Path(dp) / fn
                if exclude and p.resolve() == Path(exclude).resolve():
                    continue
                d = probe_duration(p)
                if abs(d - seconds) <= tol:
                    out.append((p.stat().st_mtime, p, d))
    out.sort(reverse=True)
    return [(p, d) for _, p, d in out[:limit]]


def baked_layer(video, events, tol=0.03):
    """Does the render's own audio already contain a sound at the declared events?
    Returns dict: onset share at the events, the same at shifted copies (chance), energy at the events and at a
    shifted copy relative to the median level, and the share of the film that is quiet."""
    ons, dur = onsets(video)
    ons = [o[0] for o in ons]
    if not events:
        return None
    ts = sorted({round(e["t"], 3) for e in events})
    if len(ts) > 120:
        ts = ts[:: max(1, len(ts) // 120)]

    def share(shift):
        return sum(1 for t in ts if any(abs(o - (t + shift)) <= tol for o in ons)) / len(ts)
    pcm, rate = decode_mono(video, 16000)
    env = envelope(pcm, rate, 0.01)
    if not env:
        return None
    med = sorted(env)[len(env) // 2]

    def level(shift):
        vals = []
        for t in ts:
            a_ = max(0, int((t + shift - 0.02) / 0.01))
            b_ = min(len(env), int((t + shift + 0.06) / 0.01) + 1)
            vals.append(max(env[a_:b_]) if b_ > a_ else -120.0)
        vals.sort()
        return vals[len(vals) // 2] - med
    quiet = sum(1 for e in env if e < -55.0) / len(env)
    return {"share": share(0.0), "chance": (share(0.31) + share(0.53)) / 2, "at_db": level(0.0),
            "shifted_db": (level(0.37) + level(0.61)) / 2, "quiet": quiet}


def synth_peak_times(audio_files, events, kinds=("whoosh", "wipe"), rejected=None):
    """For each whoosh/wipe event: when does the synthesized sound really peak, and how long does it last? In some
    projects `t` is the peak (the synth starts before it), in others the start. The author heard and synchronised to
    the real peak, so that is the time the replacement has to hit. Other whooshes, hits and risers close by make the
    event "not clean"; ticks, pops and keys do not (the envelope is smoothed over 70 ms: a whoosh is a swell, they
    are transients). A peak that is really ANOTHER declared sound (a pop or a bell that is louder than the swell
    inside the window) or a move longer than the sound itself is not taken: the declared time stays, and the
    refusal goes to `rejected` as (event index, peak time, reason). Returns {event index: (peak time, length)}."""
    env = None
    for f in audio_files:
        pcm, rate = decode_mono(f, 16000)
        e = envelope(pcm, rate, 0.01)
        env = e if env is None else [max(a, b) for a, b in zip(env, e)] + (e[len(env):] if len(e) > len(env) else [])
    if not env:
        return {}
    lin = [10 ** (v / 20.0) for v in env]
    half = 3
    sm = []
    for i in range(len(lin)):
        seg = lin[max(0, i - half):i + half + 1]
        v = sum(seg) / len(seg)
        sm.append(20 * math.log10(v) if v > 1e-5 else -100.0)
    heavy = {"whoosh", "wipe", "hit", "thump", "riser", "drop", "magic", "ambience", "glitch", "camera", "shatter"}
    blockers = sorted((e["t"], i) for i, e in enumerate(events) if e["ck"] in heavy)
    declared = sorted((e["t"], i) for i, e in enumerate(events))
    out = {}
    for i, e in enumerate(events):
        if e["ck"] not in kinds:
            continue
        span = e["len"] or 0.5
        if any(abs(t - e["t"]) > 1e-6 and e["t"] - 0.15 <= t <= e["t"] + span + 0.15 for t, j in blockers if j != i):
            continue                                     # another big sound inside the window: not clean
        a0 = max(0, int((e["t"] - 0.25) / 0.01))
        b0 = min(len(sm), int((e["t"] + span + 0.30) / 0.01))
        seg = sm[a0:b0]
        if len(seg) < 5 or max(seg) < -55.0:
            continue
        k = seg.index(max(seg))
        peak_t = (a0 + k + 0.5) * 0.01
        top = seg[k]
        lo = k
        while lo > 0 and seg[lo - 1] >= top - 20.0:
            lo -= 1
        hi = k
        while hi < len(seg) - 1 and seg[hi + 1] >= top - 20.0:
            hi += 1
        width = round(max(0.2, min(2.5, (hi - lo + 1) * 0.01)), 2)
        d_ = peak_t - e["t"]
        near = [j for t_, j in declared if j != i and abs(t_ - peak_t) <= 0.08 and abs(t_ - e["t"]) > 0.08]
        cap = min(1.0, max(0.4, span + 0.1))                  # the peak lies inside the sound's own length
        i_t = min(len(sm) - 1, max(0, int(e["t"] / 0.01)))
        i_p = min(len(sm) - 1, max(0, int(round(peak_t / 0.01))))
        at_t = sm[i_t]
        lo_i, hi_i = (i_t, i_p) if i_t <= i_p else (i_p, i_t)
        valley = min(sm[lo_i:hi_i + 1]) if hi_i > lo_i else at_t
        # a swell that rises all the way from the declared time to the peak is ONE sound (it lands on a click: fine);
        # a dip on the way means the loudest point is another sound; a declared pop/bell at that peak while the whoosh
        # already sounds loudly at its declared time means the declared time was its centre
        # (the declared time must itself carry a sound within 25 dB of that peak: a whoosh that starts after a short
        # silence has nothing at its declared time, and the dip is only the gap before its own swell)
        separate = abs(d_) >= 0.15 and valley < at_t - 6.0 and at_t >= top - 25.0
        landing = bool(near) and at_t >= top - 12.0
        if (separate or landing) and abs(d_) >= 0.04:
            if rejected is not None:
                if separate:
                    why_ = (f"the level dips {at_t - valley:.0f} dB between the declared time and that peak: a "
                            f"different sound sits there")
                else:
                    j = near[0]
                    why_ = (f"another declared sound ({events[j]['kind']} at {events[j]['t']:.2f} s) sits at that peak "
                            f"and the whoosh already sounds at its declared time (that time is its centre)")
                rejected.append((i, peak_t, why_))
            out[i] = (e["t"], width)
        elif abs(d_) > cap:
            if rejected is not None:
                rejected.append((i, peak_t, f"a move of {d_:+.2f} s is longer than the sound ({span:.2f} s)"))
            out[i] = (e["t"], width)
        elif at_t >= top - 2.0 and abs(d_) < 0.3:           # it already sounds at its loudest where it was declared
            out[i] = (e["t"], width)
        else:
            out[i] = (peak_t, width)
    return out


# ------------------------------------------------------------------ a time map from the synthesized onsets
PRECISE_EXCLUDE = {"whoosh", "wipe", "riser", "ambience", "magic"}      # their `t` is a start, a peak or a tail


def synth_onsets(files, min_level=-30.0):
    """Sorted [(time, level dB under that stem's loudest)] of the separate sounds of the synthesized stems."""
    out = []
    for f in files:
        ons, _ = onsets(f)
        out += [(t_, l_) for t_, l_ in ons if l_ >= min_level]
    out.sort()
    merged = []
    for t_, l_ in out:
        if merged and t_ - merged[-1][0] < 0.02:
            if l_ > merged[-1][1]:
                merged[-1] = (merged[-1][0], l_)
            continue
        merged.append((t_, l_))
    return merged


def _hit(onset_ts, t, tol):
    import bisect
    j = bisect.bisect_left(onset_ts, t - tol)
    return j < len(onset_ts) and onset_ts[j] <= t + tol


def estimate_time_map(times, onset_ts, win=6.0, hop=2.0, lag_lo=-2.5, lag_hi=4.5, step=0.02, tol=0.045,
                      lam=4.0):
    """Where does a declared time land in THIS render? The score of a synthesizing project is built from its list, so
    every declared event has an onset in the synthesized stems, at the list's time plus an offset that a re-time
    (a voice fit, a cut) makes different along the film. For windows of the list, every candidate offset gets the
    number of events that meet an onset; the path through the windows that keeps most of them while the offset
    changes slowly (a change costs `lam` events per second of offset) is the map (a Viterbi pass).
    Returns (centers, offsets) or None."""
    times = sorted(times)
    if len(times) < 4 or not onset_ts:
        return None
    lags = [lag_lo + step * k for k in range(int((lag_hi - lag_lo) / step) + 1)]
    n = len(lags)
    centers, emis = [], []
    c = 0.0
    while c <= times[-1] + hop:
        ev = [x for x in times if abs(x - c) <= win / 2]
        centers.append(c)
        emis.append([sum(1 for x in ev if _hit(onset_ts, x + d, tol)) for d in lags] if len(ev) >= 3 else None)
        c += hop
    if sum(1 for e in emis if e is not None) < 2:
        return None
    pen = lam * step
    score = [-0.3 * abs(d) for d in lags]                # the first window prefers an offset near zero
    back = []
    for e in emis:
        fwd, arg = score[:], list(range(n))
        for j in range(1, n):
            cand = fwd[j - 1] - pen
            if cand > fwd[j]:
                fwd[j], arg[j] = cand, arg[j - 1]
        for j in range(n - 2, -1, -1):
            cand = fwd[j + 1] - pen
            if cand > fwd[j]:
                fwd[j], arg[j] = cand, arg[j + 1]
        back.append(arg)
        score = [fwd[j] + (e[j] if e else 0) for j in range(n)]
    j = max(range(n), key=lambda k: score[k])
    path = [j]
    for arg in reversed(back[1:]):
        j = arg[j]
        path.append(j)
    path.reverse()
    offs = [round(lags[k], 3) for k in path]
    # windows without events are carried by their neighbours: keep only the ones that had evidence
    keep = [i for i, e in enumerate(emis) if e is not None]
    return [centers[i] for i in keep], [offs[i] for i in keep]


def pchip_map(pairs, step=0.1):
    """A project's own warp (warp.cjs: a monotone cubic through [film_t, design_t] anchors, W its inverse by
    bisection) as (centers, offsets) in design time: film = design + offset. Same formulas, so the times match the
    ones its score was synthesized at."""
    pts = sorted((float(a_), float(b_)) for a_, b_ in pairs)
    xs, ys = [p_[0] for p_ in pts], [p_[1] for p_ in pts]
    n = len(xs)
    if n < 2:
        return None
    h = [xs[i + 1] - xs[i] for i in range(n - 1)]
    if any(v <= 0 for v in h):
        return None
    d = [(ys[i + 1] - ys[i]) / h[i] for i in range(n - 1)]
    m = [0.0] * n
    m[0], m[n - 1] = d[0], d[n - 2]
    for i in range(1, n - 1):
        w1, w2 = 2 * h[i] + h[i - 1], h[i] + 2 * h[i - 1]
        m[i] = 0.0 if d[i - 1] * d[i] <= 0 else (w1 + w2) / (w1 / d[i - 1] + w2 / d[i])

    def map_t(tau):
        if tau <= xs[0]:
            return ys[0]
        if tau >= xs[-1]:
            return ys[-1]
        for i in range(1, n):
            if tau <= xs[i]:
                x0, y0, x1, y1 = xs[i - 1], ys[i - 1], xs[i], ys[i]
                hh = x1 - x0
                u = (tau - x0) / hh
                return ((2 * u ** 3 - 3 * u * u + 1) * y0 + (u ** 3 - 2 * u * u + u) * hh * m[i - 1]
                        + (3 * u * u - 2 * u ** 3) * y1 + (u ** 3 - u * u) * hh * m[i])
        return ys[-1]

    centers, offs = [], []
    t = ys[0]
    while t <= ys[-1] + 1e-9:
        lo, hi = xs[0], xs[-1]
        for _ in range(50):
            mid = (lo + hi) / 2
            if map_t(mid) < t:
                lo = mid
            else:
                hi = mid
        centers.append(round(t, 4))
        offs.append(round((lo + hi) / 2 - t, 4))
        t += step
    return centers, offs


def find_project_anchors(root):
    """A project that re-times its list after the voice fit usually keeps the map next to its sources: a file
    timing.js / timing.json / timemap.* with {"anchors": [[design_t, actual_t], ...]}. (pairs, path) or None."""
    import re as _re
    name = _re.compile(r"^(timing|timemap|time_map|retime|timewarp)\.(js|mjs|cjs|ts|json)$", _re.I)
    skip = SKIP_DIRS - {"assets"}                 # assets/timing.json is where a generated project keeps it
    for dp, dns, fns in os.walk(root):
        dns[:] = [d for d in dns if d not in skip and len(Path(dp, d).relative_to(root).parts) < 4]
        for fn in fns:
            if not name.match(fn):
                continue
            try:
                s = (Path(dp) / fn).read_text(encoding="utf-8", errors="replace")
                d = json.loads(s[s.index("{"): s.rindex("}") + 1])
            except (ValueError, OSError):
                continue
            pairs = d.get("anchors") if isinstance(d, dict) else None
            if pairs is None and isinstance(d, dict):
                for key_ in ("WARP", "warp", "ANCHORS"):
                    w_ = d.get(key_)
                    if isinstance(w_, list) and len(w_) >= 2 and all(isinstance(x, list) and len(x) == 2 for x in w_):
                        try:   # {DUR, WARP: [[film_t, design_t], ...]}: the coordinate that ends at DUR is film time
                            film_first = abs(float(w_[-1][0]) - float(d.get("DUR", -1))) < 0.05
                        except (TypeError, ValueError):
                            film_first = False
                        pairs = [[x[1], x[0]] for x in w_] if film_first else w_
                        if film_first and key_ == "WARP":
                            dense = pchip_map(w_)                 # the project's own monotone cubic, not a polyline
                            if dense:
                                return dense, Path(dp) / fn
                        break
            if isinstance(pairs, list) and len(pairs) >= 2 and all(isinstance(x, list) and len(x) == 2 for x in pairs):
                pts = sorted((float(x[0]), float(x[1])) for x in pairs)
                return ([q[0] for q in pts], [q[1] - q[0] for q in pts]), Path(dp) / fn
    return None


def assign_onsets(ms, ons, tol=0.2, same=0.012):
    """Monotone one-to-one matching of mapped event times `ms` (sorted) to synthesized onsets `ons` (sorted): the
    total distance is minimal, an event with no onset within `tol` stays unmatched. Events closer than `same` to the
    previous one are the same moment (a layer) and take its onset. Returns a list: onset time or None per event."""
    groups = []
    for i, m in enumerate(ms):
        if groups and m - ms[groups[-1][0]] <= same:
            groups[-1].append(i)
        else:
            groups.append([i])
    G, K = len(groups), len(ons)
    INF = float("inf")
    dp = [[INF] * (K + 1) for _ in range(G + 1)]
    src = [[None] * (K + 1) for _ in range(G + 1)]
    dp[0][0] = 0.0
    for g in range(G + 1):
        for j in range(K):                                   # onsets may be skipped for free
            if dp[g][j] < dp[g][j + 1]:
                dp[g][j + 1] = dp[g][j]
                src[g][j + 1] = ("skip", j)
        if g == G:
            break
        m = ms[groups[g][0]]
        for j in range(K + 1):
            c0 = dp[g][j]
            if c0 == INF:
                continue
            if c0 + tol < dp[g + 1][j]:
                dp[g + 1][j] = c0 + tol
                src[g + 1][j] = ("none", j)
            if j < K and abs(ons[j] - m) <= tol and c0 + abs(ons[j] - m) < dp[g + 1][j + 1]:
                dp[g + 1][j + 1] = c0 + abs(ons[j] - m)
                src[g + 1][j + 1] = ("match", j)
    j = min(range(K + 1), key=lambda x: dp[G][x])
    g = G
    pick = [None] * G
    while g > 0 or (g == 0 and src[0][j] is not None):
        kind, jp = src[g][j]
        if kind == "skip":
            j = jp
        elif kind == "none":
            g -= 1
            j = jp
        else:
            g -= 1
            pick[g] = ons[jp]
            j = jp
        if g == 0 and src[0][j] is None:
            break
    out = [None] * len(ms)
    for gi, grp in enumerate(groups):
        for i in grp:
            out[i] = pick[gi]
    return out


def map_time(x, centers, offs):
    if x <= centers[0]:
        return x + offs[0]
    if x >= centers[-1]:
        return x + offs[-1]
    for i in range(1, len(centers)):
        if x <= centers[i]:
            f = (x - centers[i - 1]) / max(1e-9, centers[i] - centers[i - 1])
            return x + offs[i - 1] + f * (offs[i] - offs[i - 1])
    return x + offs[-1]


