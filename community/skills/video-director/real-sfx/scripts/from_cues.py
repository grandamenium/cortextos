def clean_pool(index, kinds, used, taste, need=18, max_files=12):
    """Clean single hits of the best foley recordings for the given physical kinds, one recording family first (a
    ball is one object: its takes are the takes of one family). [{file, id, name, start, len, zcr, level_db, role}]"""
    from common import clean_hits
    specs = []
    for k in kinds:
        specs += PHYS_SPECS.get(k, [])
    seen, pool, fam0 = set(), [], None
    for spec in specs:
        for _, s in rank(index, spec, used, taste)[:max_files]:
            if s["path"] in seen:
                continue
            seen.add(s["path"])
            fk = (s["library"], family_key(s["name"]))
            fam0 = fam0 or fk
            hits, _ = clean_hits(s["path"])
            for h in hits:
                if h["clean"]:
                    pool.append(dict(h, file=s["path"], id=s["id"], name=s["name"], role=spec.get("role", "foley"),
                                     same_family=(fk == fam0)))
        if len(pool) >= need:
            break
    same = [h for h in pool if h["same_family"]]
    return same if len(same) >= 4 else pool


def bank_from_ids(index, ids):
    """Single hits of the named sounds: the clean ones, else every separate sound (granular material: poured beads)."""
    from common import clean_hits
    out = []
    for i in ids:
        s = next((x for x in index if x["id"] == i), None)
        if s is None:
            sys.exit(f"--kind ...=slices:{i}: no sound with that id in the index")
        hits, _ = clean_hits(s["path"])
        good = [h for h in hits if h["clean"]] or [h for h in hits if h["level_db"] >= -18.0]
        if not good:                                   # a sound that is one hit from its first sample: all of it
            good = [{"t": 0.0, "start": 0.0, "len": round(min(0.3, max(0.04, effective_dur(s))), 3), "level_db": 0.0,
                     "clean": True, "decay_ms": 0, "zcr": 0}]
        for h in good:
            out.append(dict(h, file=s["path"], id=s["id"], name=s["name"], role=s.get("role", "foley"),
                            len=round(min(h["len"], 0.12), 3) if not h["clean"] else h["len"],
                            abs_db=round((s.get("peak_db") or 0.0) + h.get("level_db", 0.0), 1)))
    bank_from_ids.dropped = 0
    if len(out) >= 6:                    # the quietest slices come up with their noise: leave them out of the bank
        top = max(h["abs_db"] for h in out)
        keep = [h for h in out if h["abs_db"] >= top - 12.0]
        if len(keep) >= 4:
            bank_from_ids.dropped = len(out) - len(keep)
            out = keep
    return out


def parse_kind_arg(text):
    """'bead=click' -> ('bead', 'click');  'zap=role:glitch,max_dur=0.6' -> a pick;  'boop=uisfx:select' -> uisfx."""
    name, _, target = str(text).partition("=")
    name = name.strip().lower().replace("-", "_").replace(" ", "_")
    target = target.strip()
    if not name or not target:
        sys.exit(f"--kind expects NAME=TARGET (bead=click, zap=role:glitch,max_dur=0.6), got {text!r}")
    if target.startswith("role:"):
        parts = target[5:].split(",")
        pick = {"role": parts[0].strip()}
        for kv in parts[1:]:
            k, _, v = kv.partition("=")
            v = v.strip()
            try:
                pick[k.strip()] = float(v) if "." in v else int(v)
            except ValueError:
                pick[k.strip()] = {"true": True, "false": False}.get(v.lower(), v)
        return name, {"pick": pick}
    if target.startswith("uisfx:"):
        return name, {"uisfx": target[6:].strip()}
    if target.startswith("slices:"):                   # bead=slices:740,763: the clean single hits of these sounds
        ids = [int(x) for x in target[7:].replace(" ", "").split(",") if x.strip().isdigit()]
        if not ids:
            sys.exit(f"--kind {text!r}: slices: wants ids from search.py (bead=slices:740,763)")
        return name, {"bank_ids": ids}
    return name, target


def canon(raw):
    k = str(raw or "").strip().lower().replace("-", "_").replace(" ", "_")
    return CANON.get(k, k)


def load_events(path):
    d = load_json(path)
    if isinstance(d, dict):
        d = d.get("cues") or d.get("events") or d.get("sounds") or []
    out = []
    for e in d:
        if not isinstance(e, dict):
            continue
        t = next((e[k] for k in ("t", "time", "at", "start") if k in e), None)
        kind = next((e[k] for k in ("type", "name", "kind", "event", "sound") if k in e), None)
        if t is None or kind is None:
            continue
        g = next((e[k] for k in ("g", "gain", "volume", "vol") if k in e), 1.0)
        ln = next((e[k] for k in ("len", "dur", "duration", "length") if k in e), None)
        out.append({"t": float(t), "kind": str(kind), "g": float(g), "len": float(ln) if ln is not None else None,
                    "raw": e})
    return sorted(out, key=lambda x: x["t"])


def find_cue_list(folder):
    """The project's own typed cue list inside a project folder: a JSON file named like cues / events with entries
    that have a time and a kind (docs/cues.json, scripts/cues.json, assets/cues.json ...). The one with the most
    events wins. None when there is none (then the synthesizer script is the source)."""
    best = None
    root = Path(folder)
    for sub in ("docs", "scripts", "assets", "audio", "data", "src", "."):
        d = root / sub
        if not d.is_dir():
            continue
        for p in sorted(d.glob("*.json")):
            if not re.search(r"cue|event", p.stem, re.I):
                continue
            try:
                ev = load_events(p)
            except (OSError, ValueError, TypeError, AttributeError):
                continue
            if len(ev) >= 3 and (best is None or len(ev) > best[0]):
                best = (len(ev), p)
    return best[1] if best else None


