def detect_typing_runs(events, min_n=8, lo=0.035, hi=0.17, min_span=0.4):
    """Runs of plain `click` events that are a person typing: at least `min_n` of them, every gap 35-170 ms, the run
    at least 0.4 s long. Returns a list of runs (lists of events)."""
    clicks = [e for e in sorted(events, key=lambda x: x["t"])
              if e.get("ck") == "click" and e.get("ck0") == "click" and not e.get("custom")]
    runs, cur = [], []
    for e in clicks:
        if cur and lo <= e["t"] - cur[-1]["t"] <= hi:
            cur.append(e)
        else:
            if len(cur) >= min_n:
                runs.append(cur)
            cur = [e]
    if len(cur) >= min_n:
        runs.append(cur)
    # animated typing in a film is as regular as a metronome (every third character, 62 ms apart): regularity says
    # nothing, the pace and the length of the row do
    return [r for r in runs if r[-1]["t"] - r[0]["t"] >= min_span]


def melody_pitches(events):
    """The author's own frequencies of a kind (a rising run of ticks, `tick(t, 1800 * 2 ** (4 * i / 12))`) as
    semitone offsets from the median, in event['_melody']. A real recording cannot take the frequency, it takes the
    interval: the melody survives the replacement. Returns the number of events that got one."""
    by = {}
    for e in events:
        raw = e.get("raw") if isinstance(e.get("raw"), dict) else {}
        f = next((raw[k] for k in ("freq", "f", "hz", "frequency") if isinstance(raw.get(k), (int, float))
                  and raw[k] > 0), None)
        if f is not None:
            by.setdefault(e["ck"], []).append((e, float(f)))
    n = 0
    for lst in by.values():
        fs = sorted(f for _, f in lst)
        if len(lst) < 3 or fs[-1] < fs[0] * 1.03:
            continue
        med = fs[len(fs) // 2]
        for e, f in lst:
            e["_melody"] = round(max(-12.0, min(12.0, 12.0 * math.log2(f / med))), 1)
            n += 1
    return n


def project_root(cue_path):
    """The folder of the project a cue list belongs to: the nearest parent with index.html / hyperframes.json."""
    d = Path(cue_path).resolve().parent
    for cand in [d] + list(d.parents)[:4]:
        if (cand / "index.html").exists() or (cand / "hyperframes.json").exists() or (cand / "package.json").exists():
            return cand
    return d


def kind_definitions(root, kinds, per_kind=2):
    """Where does the project itself define a kind? Lines of its code that mention it, definitions (a branch or a
    case on the kind) before the places that merely create such a cue, so the intent of a custom kind ('bead',
    'soft') is read from the synthesis code and not guessed."""
    found = {k: [] for k in kinds}
    if not kinds:
        return {}
    quoted = {k: re.compile(r"[\"']" + re.escape(k) + r"[\"']") for k in kinds}
    branch = {k: re.compile(r"(===?|case|==|in)\s*[\"']" + re.escape(k) + r"[\"']|[\"']" + re.escape(k)
                            + r"[\"']\s*:") for k in kinds}
    for dp, dns, fns in os.walk(root):
        dns[:] = [d for d in dns if d not in SKIP_DIRS]
        for fn in fns:
            if not fn.endswith((".js", ".cjs", ".mjs", ".ts", ".py", ".html")):
                continue
            p = Path(dp) / fn
            try:
                if p.stat().st_size > 400_000:
                    continue
                lines = p.read_text(encoding="utf-8", errors="replace").splitlines()
            except OSError:
                continue
            for i, ln in enumerate(lines):
                for k, rx in quoted.items():
                    if not rx.search(ln):
                        continue
                    prio = 0 if branch[k].search(ln) else 1
                    nxt = lines[i + 1].strip() if i + 1 < len(lines) and lines[i + 1].strip().startswith(("//", "#")) else ""
                    prev = lines[i - 1].strip() if i and lines[i - 1].strip().startswith(("//", "#", "/*", "*")) else ""
                    txt = "  ".join(x for x in (prev, ln.strip(), nxt) if x)
                    found[k].append((prio, len(found[k]), f"{p.relative_to(root).as_posix()}:{i + 1}: {txt[:200]}"))
    return {k: [t for _, _, t in sorted(v)[:per_kind]] for k, v in found.items()}


