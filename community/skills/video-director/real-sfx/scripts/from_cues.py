#!/usr/bin/env python3
"""Turn a project's own typed cue list into a cue sheet with REAL sounds on the same timestamps.

  python from_cues.py docs/cues.json --video renders/film.mp4 --out work/cues.json
                      [--ui auto|uisfx|library] [--max-rate 14] [--moments work/moments/moments.json]
                      [--map my_map.json [--remember]] [--only key,click] [--skip tick]

Why: a film that is generated by code (HyperFrames, Remotion, a "film as a function of time" engine) usually
knows what happens when. If the project already writes a design-time cue list, that list is better than any
frame analysis: exact times, and the kind of event (a keystroke, a click, a wipe, a coin) is stated, not guessed.
The projects written for a synthesised score keep such a list; this script keeps its times and kinds and swaps the
synthesis for sounds from the library (never synthesised) and uisfx (UI moments).

Input: a JSON list (or {"cues": [...]} / {"events": [...]}) of objects. Recognised keys:
  time    t | time | at | start                 seconds on the video timeline
  kind    type | name | kind | event | sound    see ALIASES below; unknown kinds are listed, never guessed
  gain    g | gain | volume | vol               1.0 = nominal; becomes dB relative to the role's level
  length  len | dur | duration | length         seconds (riser build-up, whoosh length)

What it also does, because the list is only half of the truth:
  * checks that the list belongs to THIS render (structural events must sit on picture changes) and where it
    drifts (a re-time or voice fit moves the end of a list first);
  * finds the project's audio stems and checks that they belong to this render too (duration, and the shape of
    the loudness over time); stems of another cut would put another voice and music under the new sounds;
  * says whether the render's own audio already holds the synthesized layer (the new sounds must replace it, not
    double it) and whether there is a voice in the render at all;
  * moves whooshes to where the synthesized sound really peaked (the author synchronised to what he heard);
  * turns runs of "key" events into single REAL keystrokes cut out of the library's typing recordings.

--map file.json  extends or overrides the table: {"zap": "glitch", "boop": {"uisfx": "select"},
                 "stomp": {"pick": {"role": "hit", "dark": true}, "gain_db": 2}}   (--remember keeps it)
--moments        optional: picture moments (find_moments.py) with no sound within 150 ms are listed,
                 so strong events the project forgot to declare do not stay silent.
"""
