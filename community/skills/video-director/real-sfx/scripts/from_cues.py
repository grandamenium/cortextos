def keystroke_bank(index, rng, need=120):
    """Slices (file, start, length) of single keystrokes from real typing recordings, shuffled. ONE keyboard for a
    film (a person types on one keyboard); a long take is the natural bank, a second one is added only when the
    first has fewer keystrokes than the film needs."""
    def typing_like(s):
        return ((s["role"] in ("typing", "click", "foley", "ui", "data") or "typing" in s.get("roles", []))
                and any(w in (s["name"] + " " + s["folder"]).lower()
                        for w in ("keyboard", "typing", "typewriter", "клав", "печат")))

    cands = [s for s in index if typing_like(s) and 0.7 <= effective_dur(s) <= 90.0]
    loud = [s for s in cands if s.get("peak_db", 0) >= -20.0]
    if loud:                                 # a take recorded at a sane level (normalising a quiet one raises its noise)
        cands = loud
    # the main libraries before the fallback ones, a real keyboard before a phone, the longer take before the
    # shorter (more keystrokes, more variety)
    cands.sort(key=lambda s: (s.get("tier", "main") != "main", "phone" in s["name"].lower()
                              or "phone" in s["folder"].lower(), -effective_dur(s), s["id"]))
    bank, used_takes = [], []
    for s in cands[:6]:
        ons, _ = onsets(s["path"])
        part = []
        for i, (o, lvl) in enumerate(ons):
            nxt = ons[i + 1][0] if i + 1 < len(ons) else o + 0.2
            length = min(0.085, nxt - o - 0.004)
            if length >= 0.04 and lvl >= -14.0:             # faint blips are room noise, not keystrokes
                # the natural spread between hard and soft keys is kept (compressed): every slice is normalised
                # later, so its place in the take's dynamics travels as a gain offset
                part.append({"file": s["path"], "id": s["id"], "start": max(0.0, o - 0.006), "len": round(length, 3),
                             "name": s["name"], "rel_db": round(max(-6.0, 0.5 * lvl), 1)})
        if part:
            bank += part
            used_takes.append(s["name"])
        if len(bank) >= need:
            break
    if len(bank) < need:
        # keystrokes that were cut already (a sorted pack): one file is one key. A phone keyboard is left out here
        # (it is another instrument: map 'key' to it on purpose for a phone interface)
        singles = [s for s in index if typing_like(s) and 0.03 <= effective_dur(s) < 0.7
                   and (s.get("onset_count") is None or s["onset_count"] <= 1)
                   and "phone" not in (s["name"] + " " + s["folder"]).lower()
                   and s.get("peak_db", 0) >= -30.0]
        singles.sort(key=lambda s: (s.get("tier", "main") != "main", s["id"]))
        for s in singles[: need - len(bank)]:
            ons, _ = onsets(s["path"])
            t0 = ons[0][0] if ons else 0.0
            ln = round(min(0.085, max(0.03, effective_dur(s) - t0)), 3)
            bank.append({"file": s["path"], "id": s["id"], "start": max(0.0, t0 - 0.006), "len": ln,
                         "name": s["name"], "rel_db": 0.0})
    rng.shuffle(bank)
    return bank


# ------------------------------------------------------------------ does the list belong to this render?
# structural events: a scene wipe, a stamp, a hit happen ON a picture change. Whooshes and UI ticks are placed
# relative to motion by design (mid-flight, a few frames after a click), so they say nothing about alignment.
SYNC_KINDS = {"wipe", "thump", "hit", "drop", "camera"}


def picture_sync(events, moments, tol=0.12, win=0.6):
    """Compare the declared structural events with what the picture does. A cue list written for an earlier
    cut of the film (before the voice-over was fitted, before a re-time) silently lands late or early, and the
    END of a list drifts first: the offsets are also given per quarter of the film."""
    pic = [m["t"] for m in moments if m["kind"] in ("cut", "burst", "onset", "settle")]
    offs, total, timed = [], 0, []
    for e in events:
        if e["ck"] not in SYNC_KINDS:
            continue
        total += 1
        near = min(pic, key=lambda t: abs(t - e["t"]), default=None)
        if near is not None and abs(near - e["t"]) <= win:
            offs.append(near - e["t"])
            timed.append((e["t"], near - e["t"]))
    if total < 3 or len(offs) < 2:
        return {"verdict": "unknown", "total": total, "matched": len(offs)}
    offs_sorted = sorted(offs)
    med = offs_sorted[len(offs_sorted) // 2]
    within = sum(1 for o in offs if abs(o) <= tol) / total
    adjusted = sum(1 for o in offs if abs(o - med) <= tol) / total
    if within >= 0.6:
        verdict = "ok"
    elif adjusted >= 0.6 and abs(med) >= 0.06:
        verdict = "shift"
    else:
        verdict = "mismatch"
    # drift: median offset in each quarter of the declared events (by time)
    quarters = []
    if len(timed) >= 6:
        timed.sort()
        q = max(2, len(timed) // 4)
        for i in range(0, len(timed), q):
            chunk = timed[i:i + q] if i + 2 * q <= len(timed) else timed[i:]
            quarters.append({"from": round(chunk[0][0], 1), "to": round(chunk[-1][0], 1),
                             "median_offset_s": round(sorted(o for _, o in chunk)[len(chunk) // 2], 3),
                             "n": len(chunk)})
            if i + 2 * q > len(timed):
                break
    drift = bool(len(quarters) >= 3 and max(x["median_offset_s"] for x in quarters)
                 - min(x["median_offset_s"] for x in quarters) > 0.12)
    return {"verdict": verdict, "total": total, "matched": len(offs), "median_offset_s": round(med, 3),
            "within_tol": round(within, 2), "within_after_shift": round(adjusted, 2), "quarters": quarters,
            "drift": drift}


