def find_scripts(root):
    """Candidate synthesizer scripts of a project: JS files that write a WAV or a sample buffer."""
    root = Path(root)
    out = []
    for sub in SCRIPT_DIRS:
        d = root / sub
        if not d.is_dir():
            continue
        depth0 = len(d.parts)
        for dp, dns, fns in os.walk(d):
            dns[:] = [x for x in dns if x not in SKIP and len(Path(dp, x).parts) - depth0 < 3]
            for fn in fns:
                if not fn.endswith((".cjs", ".js")):
                    continue
                p = Path(dp) / fn
                try:
                    if p.stat().st_size > 300_000:
                        continue
                    t = p.read_text(encoding="utf-8", errors="replace")
                except OSError:
                    continue
                score = 0
                score += 3 if re.search(r"writeFileSync\s*\([^)]*\.wav|RIFF|Float32Array|Int16", t) else 0
                score += 2 if re.search(r"\b(SR|sampleRate|48000|44100)\b", t) else 0
                score += 1 if re.search(r"whoosh|click|bell|thump|sfx", t, re.I) else 0
                if score >= 4:
                    out.append((score + (2 if re.search(r"sfx|audio|synth|sound", fn, re.I) else 0), p))
        if out:
            break
    out.sort(key=lambda x: (-x[0], str(x[1])))
    seen, res = set(), []
    for _, p in out:
        if p.resolve() not in seen:
            seen.add(p.resolve())
            res.append(p)
    return res


def _project_dir(script):
    """Where `node scripts/audio/sfx.cjs` is run from: the nearest parent that looks like a project root."""
    p = Path(script).resolve().parent
    for cand in [p] + list(p.parents)[:4]:
        if any((cand / m).exists() for m in ("package.json", "hyperframes.json", "index.html")):
            return cand
    return p


def run_script(script, funcs, stub, work, extra_args, timeout, save_wav=None):
    src = Path(script).read_text(encoding="utf-8", errors="replace")
    swapped = Path(work) / ("instrumented_" + Path(script).name)
    swapped.write_text(instrument(src, funcs), encoding="utf-8")
    cfgp = Path(work) / "cfg.json"
    outp = Path(work) / "events_raw.json"
    if outp.exists():
        outp.unlink()
    cfgp.write_text(json.dumps({"swap": {str(Path(script).resolve()): str(swapped)}, "stub": stub,
                                "out": str(outp), "saveWav": str(save_wav) if save_wav else None}), encoding="utf-8")
    hook = Path(work) / "hook.cjs"
    hook.write_text(HOOK, encoding="utf-8")
    env = dict(os.environ, FROM_SYNTH_CFG=str(cfgp))
    r = subprocess.run(["node", "-r", str(hook), str(script)] + list(extra_args), cwd=str(_project_dir(script)),
                       capture_output=True, text=True, env=env, timeout=timeout)
    if not outp.exists():
        raise RuntimeError("the script did not run to its end: " + (r.stderr or r.stdout or "")[-400:])
    return json.loads(outp.read_text(encoding="utf-8")), r


def to_events(raw, funcs):
    """Recorded calls -> events {t, type, g, len}. Helpers (also called from inside others) are dropped."""
    meta = {f[0]: f[1] for f in funcs}
    nested = raw.get("nested", {})
    events, kinds = [], {}
    for rec in raw.get("events", []):
        name = rec["name"]
        if nested.get(name, 0) > raw.get("called", {}).get(name, 0):
            continue                                        # a helper: called more from inside effects than by the score
        if raw.get("valued", {}).get(name, 0) * 2 > raw.get("called", {}).get(name, 1):
            continue                                        # it returns a value (a gain curve): not a sound
        params = meta.get(name, [])
        args = rec.get("args", [])
        t = args[0] if args else None
        if not isinstance(t, (int, float)) or t != t or t < 0 or t > 3600:
            continue
        ev = {"t": round(float(t), 4), "type": name}
        for i, (pn, default) in enumerate(params):
            if i == 0:
                continue
            val = args[i] if i < len(args) and args[i] is not None else default
            if val is None:
                continue
            if pn.lower() in GAIN_NAMES and "g" not in ev:
                ev["g"] = round(float(val), 4)
            elif pn.lower() in LEN_NAMES and "len" not in ev:
                ev["len"] = round(float(val), 4)
            elif pn.lower() in FREQ_NAMES and "freq" not in ev and isinstance(val, (int, float)) and val > 0:
                ev["freq"] = round(float(val), 3)          # a melody of ticks: the author's frequencies
            elif pn.lower() in DIR_NAMES and "up" not in ev and isinstance(val, (bool, int, float)):
                ev["up"] = bool(val)
        events.append(ev)
        kinds[name] = kinds.get(name, 0) + 1
    events.sort(key=lambda e: e["t"])
    return events, kinds


def from_objects(raw):
    out = []
    for p in raw.get("pushed", []):
        e = {"t": round(float(p["t"]), 4), "type": p["type"]}
        if isinstance(p.get("g"), (int, float)):
            e["g"] = p["g"]
        if isinstance(p.get("len"), (int, float)):
            e["len"] = p["len"]
        out.append(e)
    out.sort(key=lambda e: e["t"])
    return out


def extract(target, bed_out=None, args=(), timeout=180, say=print):
    """Run the synthesizer script of `target` (a project folder or a script) with its effect functions recorded.
    Returns {"events", "kinds", "script", "source", "helpers", "writes", "bed"}; raises RuntimeError with a reason."""
    if not shutil.which("node"):
        raise RuntimeError("node is not in PATH: this reads Node scripts")
    t = Path(target)
    if t.is_dir():
        cands = find_scripts(t)
        if not cands:
            esm = [p for sub in SCRIPT_DIRS for p in sorted((t / sub).glob("*.mjs"))] if t.is_dir() else []
            if esm:
                raise RuntimeError(
                    f"only ES-module script(s) found ({', '.join(p.name for p in esm[:4])}): they are not run. If one "
                    f"reads the project's cue list from a file, give that list (from_cues.py FILE.json)")
            raise RuntimeError(f"no synthesizer script found under {t} (looked in scripts/, audio/ ...): give the "
                               f"script itself")
        say("synthesizer script(s): " + ", ".join(c.relative_to(t).as_posix() for c in cands[:5]))
        script = cands[0]
    else:
        script = t
    if script.suffix == ".mjs":
        raise RuntimeError(f"{script.name} is an ES module: it is not run. If it reads its list from a file, that "
                           f"file is the list.")
    src = script.read_text(encoding="utf-8", errors="replace")
    funcs = find_functions(src)
    work = Path(tempfile.mkdtemp(prefix="from_synth_"))
    try:
        raw, r = run_script(script, funcs, [], work, list(args), timeout)
        events, kinds = to_events(raw, funcs)
        source = "calls"
        if not events:
            events = from_objects(raw)
            kinds = {}
            for e in events:
                kinds[e["type"]] = kinds.get(e["type"], 0) + 1
            source = "objects pushed to arrays"
        if not events:
            raise RuntimeError("no events recorded " + (r.stderr or "")[-300:])
        names = {f[0] for f in funcs}
        helpers = sorted(k for k, v in raw.get("nested", {}).items()
                         if k in names and v > raw.get("called", {}).get(k, 0))
        out = {"events": events, "kinds": kinds, "script": str(script), "source": source, "helpers": helpers,
               "functions": [(n, [p for p, _ in ps]) for n, ps, _, _ in funcs],
               "writes": [w["path"] for w in raw.get("writes", []) if str(w["path"]).lower().endswith(".wav")],
               "bed": None}
        if bed_out and source == "calls":
            wd_full = Path(tempfile.mkdtemp(prefix="from_synth_full_"))
            wd = Path(tempfile.mkdtemp(prefix="from_synth_wav_"))
            try:
                run_script(script, funcs, [], work, list(args), timeout, save_wav=wd_full)      # everything on
                run_script(script, funcs, sorted(kinds), work, list(args), timeout, save_wav=wd)  # effects off
                made = sorted(wd.glob("*.wav"), key=lambda p: -p.stat().st_size)
                full = sorted(wd_full.glob("*.wav"), key=lambda p: -p.stat().st_size)
                if made:
                    Path(bed_out).parent.mkdir(parents=True, exist_ok=True)
                    shutil.copyfile(made[0], bed_out)
                    out["bed"] = str(bed_out)
                    if full and full[0].name == made[0].name:
                        diff = Path(bed_out).with_name("effects_only.wav")      # full minus bed: the replaced layer
                        g = (f"[0:a]{stereo_fmt(full[0])}[a];"
                             f"[1:a]{stereo_fmt(made[0])}[b];"
                             "[a][b]amerge=inputs=2,aeval=val(0)-val(2)|val(1)-val(3):c=stereo")
                        r = subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(full[0]), "-i", str(made[0]),
                                            "-filter_complex", g, "-c:a", "pcm_s24le", str(diff)],
                                           capture_output=True, text=True)
                        if r.returncode == 0 and diff.exists():
                            out["effects_wav"] = str(diff)
            finally:
                shutil.rmtree(wd, ignore_errors=True)
                shutil.rmtree(wd_full, ignore_errors=True)
        return out
    finally:
        shutil.rmtree(work, ignore_errors=True)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("target", help="a project folder (the synthesizer script is looked for) or the script itself")
    ap.add_argument("--out", help="write the event list here (JSON), default: print a summary only")
    ap.add_argument("--bed-only", metavar="OUT.wav", help="also run with the event functions off and keep that WAV")
    ap.add_argument("--args", nargs="*", default=[], help="arguments to pass to the script")
    ap.add_argument("--timeout", type=int, default=180)
    ap.add_argument("--dry", action="store_true", help="list the functions found, run nothing")
    a = ap.parse_args()
    t = Path(a.target)
    if a.dry:
        script = (find_scripts(t) or [None])[0] if t.is_dir() else t
        if script is None:
            sys.exit(f"no synthesizer script found under {t}")
        funcs = find_functions(Path(script).read_text(encoding="utf-8", errors="replace"))
        print(f"{Path(script).name}: {len(funcs)} function(s) with a time as the first parameter: "
              + ", ".join(f"{n}({', '.join(p for p, _ in ps)})" for n, ps, _, _ in funcs))
        return 0
    try:
        res = extract(a.target, a.bed_only, a.args, a.timeout)
    except RuntimeError as ex:
        print("from_synth:", ex)
        return 2
    print(f"{Path(res['script']).name}: {len(res['events'])} events from {res['source']}: "
          + ", ".join(f"{k} x{v}" for k, v in sorted(res["kinds"].items(), key=lambda kv: -kv[1])))
    if res["helpers"]:
        print("helpers (called inside other effects, not events): " + ", ".join(res["helpers"]))
    if res["writes"]:
        print("the script would write: " + ", ".join(Path(w).name for w in res["writes"][:4]) + " (not written)")
    if a.out:
        Path(a.out).parent.mkdir(parents=True, exist_ok=True)
        Path(a.out).write_text(json.dumps(res["events"], ensure_ascii=False, indent=1), encoding="utf-8")
        print("->", a.out)
    if a.bed_only:
        if res["bed"]:
            print(f"bed only ({', '.join(sorted(res['kinds']))} switched off) -> {res['bed']}")
        else:
            print("--bed-only: not available for this script (needs effect functions, and a WAV it writes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
