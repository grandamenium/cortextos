TIME_FIRST = {"t", "t0", "time", "at", "start", "when", "begin", "onset", "sec", "seconds", "ts", "tt", "tm", "tstart",
              "t_start", "startt", "start_t", "time_s"}
GAIN_NAMES = {"g", "gain", "vol", "volume", "amp", "level", "v"}
LEN_NAMES = {"len", "length", "dur", "duration", "d", "l", "sustain"}
GENERATOR_PARAMS = {"fn", "cb", "callback", "gen", "generator", "osc", "shape", "f_", "func", "sample", "env_fn"}
FREQ_NAMES = {"f", "freq", "frequency", "hz", "f0", "fq", "pitch_hz", "tone", "note_hz"}
DIR_NAMES = {"up", "rise", "rising", "dir", "direction", "ascending"}
DENY_NAMES = {"add", "mix", "render", "write", "synth", "env", "envelope", "noise", "rnd", "rand", "rng", "bp", "lp",
              "hp", "mapt", "w", "warp", "word", "at", "plan", "pan", "play", "emit", "voice", "seed", "clamp", "lerp"}
SCRIPT_DIRS = ("scripts", "script", "tools", "audio", "src", "build", ".")
SKIP = {"node_modules", ".git", "renders", "snapshots", "dist", "vendor", ".hyperframes"}


# ------------------------------------------------------------------ a small JS scanner: strings, comments, brackets
def _skip_string(src, i):
    q = src[i]
    i += 1
    n = len(src)
    while i < n:
        c = src[i]
        if c == "\\":
            i += 2
            continue
        if q == "`" and c == "$" and i + 1 < n and src[i + 1] == "{":
            i = _balanced(src, i + 1, "{", "}")
            continue
        if c == q:
            return i + 1
        i += 1
    return n


def _regex_allowed(src, i):
    j = i - 1
    while j >= 0 and src[j] in " \t\r\n":
        j -= 1
    if j < 0:
        return True
    if src[j] in "(,=:[!&|?{};+-*%<>~^":
        return True
    m = re.search(r"(?:return|typeof|case|of|in)$", src[max(0, j - 7):j + 1])
    return bool(m)


def _balanced(src, i, open_ch, close_ch):
    """src[i] == open_ch. Index just after the matching close, skipping strings, comments and regex literals."""
    n = len(src)
    depth = 0
    while i < n:
        c = src[i]
        if c in "\"'`":
            i = _skip_string(src, i)
            continue
        if c == "/" and i + 1 < n:
            d = src[i + 1]
            if d == "/":
                j = src.find("\n", i)
                i = n if j < 0 else j
                continue
            if d == "*":
                j = src.find("*/", i + 2)
                i = n if j < 0 else j + 2
                continue
            if _regex_allowed(src, i):
                j = i + 1
                in_class = False
                while j < n and src[j] != "\n":
                    if src[j] == "\\":
                        j += 2
                        continue
                    if src[j] == "[":
                        in_class = True
                    elif src[j] == "]":
                        in_class = False
                    elif src[j] == "/" and not in_class:
                        break
                    j += 1
                i = j + 1
                continue
        if c == open_ch:
            depth += 1
        elif c == close_ch:
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    return n


def _split_params(text):
    out, depth, cur, i, n = [], 0, "", 0, len(text)
    while i < n:
        c = text[i]
        if c in "\"'`":
            j = _skip_string(text, i)
            cur += text[i:j]
            i = j
            continue
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        if c == "," and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += c
        i += 1
    if cur.strip():
        out.append(cur)
    return out


def _param(p):
    p = p.strip()
    if not p or p.startswith(("{", "[", "...")):
        return None, None
    name, eq, default = p.partition("=")
    name = name.strip()
    if not re.match(r"^[A-Za-z_$][\w$]*$", name):
        return None, None
    val = None
    if eq:
        try:
            val = float(default.strip())
        except ValueError:
            val = None
    return name, val


def _statement_end(src, i):
    """End of an expression-bodied arrow function / initialiser that starts at i: a `;` at depth 0, or the end of the
    line when the next line does not continue it."""
    n = len(src)
    depth = 0
    while i < n:
        c = src[i]
        if c in "\"'`":
            i = _skip_string(src, i)
            continue
        if c == "/" and i + 1 < n and src[i + 1] in "/*":
            if src[i + 1] == "/":
                j = src.find("\n", i)
                i = n if j < 0 else j
            else:
                j = src.find("*/", i + 2)
                i = n if j < 0 else j + 2
            continue
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
            if depth < 0:
                return i
        elif c == ";" and depth == 0:
            return i + 1
        elif c == "\n" and depth == 0:
            j = i + 1
            while j < n and src[j] in " \t\r\n":
                j += 1
            nxt = src[j:j + 2]
            prev = src[:i].rstrip()[-1:] if src[:i].strip() else ""
            if not (nxt[:1] in ".?:+-*/%&|,)" or prev in "=+-*/%&|,?:(["):
                return i
        i += 1
    return n


DEF_FN = re.compile(r"(?m)^([ \t]*)(?:export\s+)?(?:async\s+)?function\s*\*?\s*([A-Za-z_$][\w$]*)\s*\(")
DEF_VAR = re.compile(r"(?m)^([ \t]*)(?:export\s+)?(const|let|var)\s+([A-Za-z_$][\w$]*)\s*=\s*"
                     r"(?:async\s+)?(?:function\s*\*?\s*[A-Za-z_$\w]*\s*)?\(")
DEF_VAR1 = re.compile(r"(?m)^([ \t]*)(?:export\s+)?(const|let|var)\s+([A-Za-z_$][\w$]*)\s*=\s*(?:async\s+)?"
                      r"([A-Za-z_$][\w$]*)\s*=>")


def find_functions(src):
    """[(name, params[(pname, default)], insert_at, kw_span)] for functions whose first parameter is a time."""
    found = []
    seen = set()

    def take(name, params, end, kw_span):
        pn = [_param(p) for p in params]
        pn = [(a, b) for a, b in pn if a]
        if not pn or pn[0][0].lower() not in TIME_FIRST:
            return
        if name.lower() in DENY_NAMES or any(a.lower() in GENERATOR_PARAMS for a, _ in pn):
            return
        if name in seen:
            return
        seen.add(name)
        found.append((name, pn, end, kw_span))

    for m in DEF_FN.finditer(src):
        po = m.end() - 1
        pe = _balanced(src, po, "(", ")")
        params = _split_params(src[po + 1:pe - 1])
        k = pe
        while k < len(src) and src[k] in " \t\r\n":
            k += 1
        if k < len(src) and src[k] == "{":
            take(m.group(2), params, _balanced(src, k, "{", "}"), None)
    for m in DEF_VAR.finditer(src):
        po = m.end() - 1
        pe = _balanced(src, po, "(", ")")
        params = _split_params(src[po + 1:pe - 1])
        k = pe
        while k < len(src) and src[k] in " \t\r\n":
            k += 1
        if src[k:k + 2] == "=>":
            k += 2
            while k < len(src) and src[k] in " \t\r\n":
                k += 1
            end = _balanced(src, k, "{", "}") if src[k:k + 1] == "{" else _statement_end(src, k)
        elif src[k:k + 1] == "{":
            end = _balanced(src, k, "{", "}")
        else:
            continue
        kw = (m.start(2), m.end(2))
        if m.group(2) == "const":
            take(m.group(3), params, end, kw)
        else:
            take(m.group(3), params, end, None)
    for m in DEF_VAR1.finditer(src):
        k = m.end()
        while k < len(src) and src[k] in " \t\r\n":
            k += 1
        end = _balanced(src, k, "{", "}") if src[k:k + 1] == "{" else _statement_end(src, k)
        kw = (m.start(2), m.end(2)) if m.group(2) == "const" else None
        take(m.group(3), [m.group(4)], end, kw)
    return found


def instrument(src, funcs):
    """Source with every found function re-bound to a recording wrapper right after its definition."""
    edits = []
    for name, params, end, kw in funcs:
        pj = json.dumps([[a, b] for a, b in params])
        edits.append((end, f"\n;{name} = globalThis.__fs_wrap({json.dumps(name)}, {name}, {pj});"))
        if kw:
            edits.append((kw[0], None, kw[1]))
    out = src
    for e in sorted(edits, key=lambda x: -x[0]):
        if e[1] is None:
            out = out[:e[0]] + "let" + out[e[2]:]
        else:
            out = out[:e[0]] + e[1] + out[e[0]:]
    return out


