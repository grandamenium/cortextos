#!/usr/bin/env python3
"""The event list of a project that synthesizes its sound in a script (Node): which sound, at what time, how loud.

  python from_synth.py PROJECT_OR_SCRIPT [--out work/events.json] [--bed-only work/bed.wav] [--args ...]

Why: a film generated by code usually has no cue file. Its sound lives in a script (audio.cjs, sfx.cjs) as calls
like `whoosh(4.2, 1, 0.3, 0.5)`, `click(18.35)`, `key(t, i)`: the TIME and the KIND of every sound are in the code,
and nowhere else in a form a tool can read. This script finds those functions, runs the script once with every
file write and child process switched off, records each outermost call (name, time, gain, length) and writes the
list in the format from_cues.py reads. Nothing in the project is changed or created.

--bed-only OUT.wav   runs the script a second time with the event functions switched OFF and keeps the WAV it
                     would have written: the author's score (music, drones, beds) without the effects. That is
                     the music to keep when it is synthesized by the same script and baked into one file, and
                     not a stem of its own (use it with mix.py --base-audio OUT.wav voice.wav --duck-music).
--dry                only list the functions it would record, run nothing.

It executes the project's own script (Node, CommonJS). The functions are found by their shape: a first parameter
that is a time (t, time, at, start ...) and no parameter that is a sample generator (fn, cb, gen ...). Functions
that are also called from inside another recorded function (the `add` that every effect uses) are helpers and
not events. A project whose cues are written as objects (`cues.push({t, type, gain})`) is read from those objects.
ES modules (.mjs) are not run: such a script usually reads its list from a file, which is then the list.
"""
